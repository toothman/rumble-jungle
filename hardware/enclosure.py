"""
Rumble Jungle - 3D printable enclosure.

Generates hardware/stl/box.stl and hardware/stl/lid.stl. Everything is
parametric: edit the values below and run

    python3 -m venv .venv && .venv/bin/pip install -r hardware/requirements.txt
    .venv/bin/python hardware/enclosure.py

Coordinate system (box interior): x from the USB-C wall (x=0) to the
Ethernet wall (x=IN_X), y from the back wall with the RCA jacks (y=0) to the
front (y=IN_Y), z up from the bottom of the floor. The perfboard layout this
box is made for is drawn in docs/perfboard.svg (generated by perfboard.py,
which shares the board geometry defined in layout.py).
"""
import math
import os

import manifold3d as m3d
import numpy as np
from matplotlib.font_manager import FontProperties
from matplotlib.textpath import TextPath

import layout as L

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "stl")

# --------------------------------------------------------------------------
# Parameters (mm)
# --------------------------------------------------------------------------
WALL = 2.4
FLOOR = 2.0
LID = 2.4
CORNER_R = 4.0              # outer corner radius
CLEAR = 1.0                 # perfboard to wall

IN_X = CLEAR + L.ESP_X0 + L.ESP_LEN + 0.3   # RJ45 face sits 0.3 mm from the inner wall
IN_Y = L.BOARD_H + 2 * CLEAR
IN_Z = 42.0                 # floor top to lid; room for the optional PoE module

STANDOFF_H = 5.0            # floor to perfboard underside
STANDOFF_D = 6.5
BOARD_SCREW_PILOT = 2.5     # M3 self-tapping (use 2.1 for M2.5)

LID_SCREW_PILOT = 2.5       # M3 x 10 self-tapping screws hold the lid
LID_SCREW_HOLE = 3.4
LID_SCREW_HEAD = 6.4        # countersink diameter
BOSS = 7.0                  # lid screw boss size
BOSS_DEPTH = 14.0

RCA_HOLE_D = 6.5            # panel RCA jack: thread diameter + 0.3 (measure yours!)
RCA_Z = 31.0                # jack centre above the bottom
RCA_X = (16.0, 30.0, 50.0, 64.0)

USB_W, USB_H = 14.0, 9.0    # opening for the USB-C plug overmould
RJ45_W, RJ45_H = 16.7, 13.5 # jack body; opening gets 0.5 mm clearance per side

EMBOSS = 0.8                # logo height on the lid
DEBOSS = 0.6                # label depth on the walls

# Derived heights
BOARD_Z = FLOOR + STANDOFF_H                       # perfboard underside
ESP_Z = BOARD_Z + L.PERFBOARD_T + L.ESP_STACK      # ESP32 PCB underside
ESP_TOP = ESP_Z + L.ESP_T
WALL_TOP = FLOOR + IN_Z

m3d.set_circular_segments(96)


def board_xy(x, y):
    """Perfboard coordinates (mm, origin top-left) -> box interior."""
    return CLEAR + x, CLEAR + y


def box_xy_of_esp(ex, ey):
    """ESP32 coordinates (mm from its USB-C edge / its pin-21..40 edge)."""
    bx, by = L.ESP_X0 + ex, L.ESP_Y0 + ey
    return board_xy(bx, by)


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------

def rrect(w, h, r):
    """Rounded rectangle from (0,0) to (w,h)."""
    r = min(r, w / 2 - 0.01, h / 2 - 0.01)
    if r <= 0:
        return m3d.CrossSection.square((w, h))
    return (m3d.CrossSection.square((w - 2 * r, h - 2 * r))
            .translate((r, r))
            .offset(r, m3d.JoinType.Round))


def box(x0, y0, z0, x1, y1, z1):
    return m3d.Manifold.cube((x1 - x0, y1 - y0, z1 - z0)).translate((x0, y0, z0))


def cyl(x, y, z0, z1, d, d2=None):
    return m3d.Manifold.cylinder(z1 - z0, d / 2, (d2 if d2 else d) / 2).translate((x, y, z0))


def text_cs(s, size, weight="bold"):
    """Text outline as a CrossSection, centred at the origin, reading +x/+y."""
    tp = TextPath((0, 0), s, size=size,
                  prop=FontProperties(family="DejaVu Sans", weight=weight))
    polys = [p[:-1].tolist() for p in tp.to_polygons() if len(p) > 3]
    cs = m3d.CrossSection(polys, m3d.FillRule.EvenOdd)
    (x0, y0, x1, y1) = cs.bounds()
    return cs.translate((-(x0 + x1) / 2, -(y0 + y1) / 2))


def wall_text(s, size, face, u, z):
    """Debossed label on an outer wall face. u runs along the wall as seen
    from outside, left to right."""
    # Text x -> to the right as seen from outside, text y -> up, the
    # extrusion points out of the wall and starts DEBOSS inside it.
    solid = text_cs(s, size).extrude(DEBOSS + 1.0)
    if face == "back":      # seen from behind, right is +x
        return solid.rotate((90, 0, 0)).translate((u, -WALL + DEBOSS, z))
    if face == "left":      # seen from the left, right is -y
        return solid.rotate((90, 0, -90)).translate((-WALL + DEBOSS, u, z))
    if face == "right":     # seen from the right, right is +y
        return solid.rotate((90, 0, 90)).translate((IN_X + WALL - DEBOSS, u, z))
    raise ValueError(face)


# --------------------------------------------------------------------------
# Box
# --------------------------------------------------------------------------

def lid_boss_positions():
    h = BOSS / 2
    return [(h, h), (IN_X - h, h), (h, IN_Y - h), (IN_X - h, IN_Y * 0.42)]


def make_box():
    outer = rrect(IN_X + 2 * WALL, IN_Y + 2 * WALL, CORNER_R).translate((-WALL, -WALL))
    inner = rrect(IN_X, IN_Y, max(CORNER_R - WALL, 0.5))
    shell = outer.extrude(WALL_TOP) - inner.extrude(WALL_TOP).translate((0, 0, FLOOR))

    # Perfboard standoffs
    for hx, hy in L.BOARD_HOLES:
        x, y = board_xy(hx, hy)
        shell += cyl(x, y, FLOOR - 0.1, BOARD_Z, STANDOFF_D)
        shell -= cyl(x, y, FLOOR - 1.0, BOARD_Z + 1, BOARD_SCREW_PILOT)

    # Lid screw bosses, hanging from the walls with a 45 degree underside
    for bx, by in lid_boss_positions():
        x0, y0 = bx - BOSS / 2, by - BOSS / 2
        z_top, z_bot = WALL_TOP, WALL_TOP - BOSS_DEPTH
        block = box(x0, y0, z_bot, x0 + BOSS, y0 + BOSS, z_top)
        # 45 degree support: hull of the block's bottom face and a line on the wall
        pts = [(x0, y0, z_bot), (x0 + BOSS, y0, z_bot),
               (x0, y0 + BOSS, z_bot), (x0 + BOSS, y0 + BOSS, z_bot)]
        wx = -0.1 if bx < IN_X / 2 else IN_X + 0.1
        pts += [(wx, y0, z_bot - BOSS), (wx, y0 + BOSS, z_bot - BOSS)]
        if by < IN_Y / 2 and by < BOSS:     # corner boss: also lean on the back wall
            pts += [(x0, -0.1, z_bot - BOSS), (x0 + BOSS, -0.1, z_bot - BOSS)]
        if by > IN_Y - BOSS:                # front corner boss
            pts += [(x0, IN_Y + 0.1, z_bot - BOSS), (x0 + BOSS, IN_Y + 0.1, z_bot - BOSS)]
        support = m3d.Manifold.hull_points(pts)
        shell += block + support
        shell -= cyl(bx, by, z_top - 12, z_top + 1, LID_SCREW_PILOT)

    # Ethernet opening (right wall)
    ry0 = box_xy_of_esp(0, L.RJ45_Y0)[1]
    shell -= box(IN_X - 1, ry0 - 0.5, ESP_TOP - 0.5,
                 IN_X + WALL + 1, ry0 + RJ45_W + 0.5, ESP_TOP + RJ45_H + 0.5)

    # USB-C opening (left wall)
    uy = box_xy_of_esp(0, L.USB_YC)[1]
    uz = ESP_TOP + 1.6
    usb = rrect(USB_W, USB_H, 2.5).translate((-USB_W / 2, -USB_H / 2)).extrude(WALL + 2)
    shell -= usb.rotate((90, 0, 90)).translate((-WALL - 1, uy, uz))

    # RCA jacks (back wall)
    for x in RCA_X:
        shell -= m3d.Manifold.cylinder(WALL + 2, RCA_HOLE_D / 2).rotate((-90, 0, 0)) \
            .translate((x, -WALL - 1, RCA_Z))

    # Labels
    shell -= wall_text("AUX 1", 4.5, "back", (RCA_X[0] + RCA_X[1]) / 2, RCA_Z + 8.5)
    shell -= wall_text("AUX 2", 4.5, "back", (RCA_X[2] + RCA_X[3]) / 2, RCA_Z + 8.5)
    for i, x in enumerate(RCA_X):
        shell -= wall_text("L" if i % 2 == 0 else "R", 4.0, "back", x, RCA_Z - 8.0)
    shell -= wall_text("USB", 4.0, "left", uy, uz + USB_H / 2 + 4.5)
    shell -= wall_text("LAN · PoE", 4.0, "right", ry0 + RJ45_W / 2, ESP_TOP + RJ45_H + 5.0)
    return shell


# --------------------------------------------------------------------------
# Lid with logo
# --------------------------------------------------------------------------

def leaf(length, width):
    """Pointed leaf along +x from the origin, with a gap for the midrib."""
    r = (length ** 2 / 4 + (width / 2) ** 2) / width       # circle through tips
    c1 = m3d.CrossSection.circle(r).translate((length / 2, -(r - width / 2)))
    c2 = m3d.CrossSection.circle(r).translate((length / 2, r - width / 2))
    shape = c1 ^ c2
    rib = m3d.CrossSection.square((length * 0.8, 0.7)).translate((length * 0.12, -0.35))
    return shape - rib


def logo():
    """Vinyl record with jungle leaves and the name, centred at the origin.
    Drawn in +x right / +y up (as seen from above, front edge at the bottom)."""
    disc_r = 23.0
    parts = [m3d.CrossSection.circle(disc_r) - m3d.CrossSection.circle(disc_r - 1.6)]
    # Grooves
    r = disc_r - 3.0
    while r > 11.5:
        parts.append(m3d.CrossSection.circle(r) - m3d.CrossSection.circle(r - 0.8))
        r -= 2.0
    # Label with spindle hole
    parts.append(m3d.CrossSection.circle(8.5) - m3d.CrossSection.circle(1.8))
    rec = m3d.CrossSection.batch_boolean(parts, m3d.OpType.Add)

    # Jungle leaves fanning out behind the record
    leaves = []
    for ang, ln, wd in ((28, 20, 10), (62, 22, 11), (96, 19, 9.5),
                        (124, 22, 11), (156, 20, 10)):
        leaves.append(leaf(ln, wd).translate((disc_r - 5, 0)).rotate(ang))
    lv = m3d.CrossSection.batch_boolean(leaves, m3d.OpType.Add)
    lv -= m3d.CrossSection.circle(disc_r + 1.4)

    title = text_cs("RUMBLE JUNGLE", 7.0).translate((0, -disc_r - 8.5))
    return rec + lv + title


def make_lid():
    w, h = IN_X + 2 * WALL, IN_Y + 2 * WALL
    plate = rrect(w, h, CORNER_R).translate((-WALL, -WALL)).extrude(LID)
    for bx, by in lid_boss_positions():
        plate -= cyl(bx, by, -1, LID + 1, LID_SCREW_HOLE)
        plate -= cyl(bx, by, LID - (LID_SCREW_HEAD - LID_SCREW_HOLE) / 2, LID + 0.01,
                     LID_SCREW_HOLE, LID_SCREW_HEAD)
    # Logo, readable from the front of the box: the viewer's right is -x and
    # "up" is the back (-y), so the drawing is turned by 180 degrees.
    lg = logo().rotate(180).translate((IN_X / 2, IN_Y / 2 - 4.0))
    keep_out = m3d.CrossSection.batch_boolean(
        [m3d.CrossSection.circle(LID_SCREW_HEAD / 2 + 1.5).translate(p)
         for p in lid_boss_positions()], m3d.OpType.Add)
    lg = (lg - keep_out) ^ rrect(IN_X + 2 * WALL - 6, IN_Y + 2 * WALL - 6, CORNER_R) \
        .translate((-WALL + 3, -WALL + 3))
    plate += lg.extrude(EMBOSS).translate((0, 0, LID))
    return plate


# --------------------------------------------------------------------------

def save_stl(man, path):
    mesh = man.to_mesh()
    v = np.asarray(mesh.vert_properties)[:, :3]
    f = np.asarray(mesh.tri_verts)
    tri = v[f]
    n = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    n /= np.linalg.norm(n, axis=1, keepdims=True) + 1e-12
    with open(path, "wb") as fh:
        fh.write(b"Rumble Jungle enclosure".ljust(80, b" "))
        fh.write(np.uint32(len(f)).tobytes())
        rec = np.zeros(len(f), dtype=[("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
        rec["n"], rec["v"] = n, tri
        fh.write(rec.tobytes())


def main():
    os.makedirs(OUT, exist_ok=True)
    b = make_box()
    lid = make_lid()
    # Lid is printed top side up: move it next to the box on the build plate
    save_stl(b.translate((WALL, WALL, 0)), os.path.join(OUT, "box.stl"))
    save_stl(lid.translate((WALL, WALL, 0)), os.path.join(OUT, "lid.stl"))
    bb = b.bounding_box()
    print(f"box: {bb[3]-bb[0]:.1f} x {bb[4]-bb[1]:.1f} x {bb[5]-bb[2]:.1f} mm, "
          f"lid {LID + EMBOSS:.1f} mm; inner {IN_X:.1f} x {IN_Y:.1f} x {IN_Z:.1f} mm")
    print(f"perfboard underside at z={BOARD_Z:.1f}, ESP32 underside at z={ESP_Z:.1f}")


if __name__ == "__main__":
    main()
